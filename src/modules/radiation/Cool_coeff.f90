      case (im_CaII); call cool_CaII(T,out)
      case (im_NaI);  call cool_NaI (T,out)
      case (im_FeI);  call cool_FeI (T,out)
      case (im_FeII); call cool_FeII(T,out)
      case default;   out = 0.0d0
   end select
   end subroutine cool_coeff_by_ion

   !--------------!

   ! Canonical mion index of an ion label (0 = unknown). Only used by the
   ! legacy name-keyed wrappers; index-based callers skip this entirely.
   integer function ion_index_of(name)
   character(len=*), intent(in) :: name
   integer :: i
   ion_index_of = 0
   do i = 1, n_mion
      if (trim(name) .eq. trim(mion_name(i))) then
         ion_index_of = i
         return
      endif
   enddo
   end function ion_index_of

