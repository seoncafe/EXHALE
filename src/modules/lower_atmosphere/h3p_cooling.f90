      module h3p_cooling
      ! Optically-thin H3+ infrared cooling (the molecular level of the lower-atmosphere
      ! plan; docs/lower_atmosphere_coupling.*).
      !
      ! THE LTE EMISSION.  W(T), the power one H3+ molecule with an LTE
      ! internal population at the gas temperature T emits into one
      ! steradian [W molecule^-1 sr^-1], is the cooling function of the
      ! MiZATeP line list (Mizus et al. 2017, MNRAS 468, 1717, section 5 and
      ! Table 7: "the total energy emitted by a single molecule in one second
      ! per unit solid angle"), tabulated at 1 K steps in the ExoMol file
      ! 1H3_p__MiZATeP.cf and carried here as h3p_mizatep_cooling_table
      ! (generated by src/utils/h3p_mizatep_cooling_table.py, which states the
      ! provenance).  The isotropic volumetric rate is
      !
      !   Lambda_H3+ = n_H3+ * 4 pi * W(T) * s(T, n_H2)   [W cm^-3]
      !   (multiply by 1e7 for erg s^-1 cm^-3),
      !
      ! the 4 pi being the one conversion from the emission into a steradian.
      !
      ! WHY NOT THE MILLER ET AL. (2013) FIT.  The LTE function of Miller,
      ! Stallard, Tennyson & Melin (2013, J. Phys. Chem. A 117, 9770,
      ! Table 5) lies above MiZATeP by a factor 1.10 at 900 K, 1.48 at
      ! 1500 K, 1.89 at 2000 K and 2.1 at 3000 K, and it is the outlier: the
      ! NMT line list those authors say they summed, summed in LTE with their
      ! own partition function, agrees with MiZATeP to 1 per cent from 300 to
      ! 2000 K and falls below their curve by nearly the same factors
      ! there (0.532 at 2000 K); their own computed Table 4 values carry
      ! the excess, so it is not the fit
      ! (md/h3p_cooling_cause_20261010.md; Mizus et al. 2017 Table 7 lists
      ! the ratio as 0.529 at 2000 K).  From 50 to 700 K the two agree to
      ! 4 per cent.
      !
      ! INTERPOLATION BETWEEN THE NODES.  ln W is linear in 1/T between
      ! adjacent 1 K nodes, i.e. each interval is a Boltzmann factor
      ! W = W_k exp[-Theta_k (1/T - 1/T_k)], the form an emission sum
      ! weighted by exp(-E_u/kT) has locally.  The table rises strictly
      ! (checked by the generator), so the interpolant is monotone and
      ! cannot overshoot a node.  MEASURED at every half-integer temperature
      ! from 20.5 to 4999.5 K against the full MiZATeP emission sum divided
      ! by its summed partition function: interpolation error at most
      ! 4.2e-4 (30-100 K), 2.3e-4 (100-300 K), 1.2e-4 (20-30 K) and 6e-7
      ! above 300 K; the file's own nodes stand within 2.7e-4 of that sum
      ! (1e-4 above 30 K).  ln W linear in T instead would be 4.3e-3 at
      ! 20-30 K and 1.2e-3 at 30-100 K.
      !
      ! TEMPERATURE DOMAIN.  The table runs from 20 K, the lowest
      ! temperature of Mizus et al. (2017) Table 7 (the file's rows below
      ! about 16 K carry the four-decimal rounding of its partition
      ! function), to 5000 K, the upper limit of the line list ("at least 99
      ! per cent complete for temperatures up to 5000 K").  Below 20 K the
      ! Boltzmann form of the first interval is continued, so W -> 0 as
      ! T -> 0 and stays monotone; it is an upper bound there (MEASURED
      ! against the full sum: 1.002 at 19 K, 1.03 at 15 K, 1.22 at 10 K, 1.5
      ! at 8 K), at a power below 1e-31 W sr^-1 that no gas of this code
      ! radiates. Above 5000 K the 5000 K value is held as an unvalidated
      ! numerical continuation. The final p18 numerical state measured on
      ! 2026-10-13 has 178 hot physical cells and Tmax = 9623.726250203 K;
      ! this is not confined to transient evaluations. Neither low abundance
      ! nor destruction
      ! validates the emission of the remaining ions. The final Bowesman
      ! et al. (2023), MNRAS 519, 6333, Table 7 retains Tmax = 5000 K.
      ! See md/AUDIT_20261013_h3p_temperature_range.md. A stationary state
      ! using this continuation is not validated by numerical residuals
      ! alone. The user-authorized conditional model explicitly assumes
      ! this held emission for the measured atmospheric range; see
      ! md/ASSUMPTIONS_20261013_stationary_physics.md, A3-A4. This assumption
      ! does not change the published-domain predicate or its output meaning.
      ! Evaluations outside 20-5000 K are
      ! recorded (h3p_evaluations_below_lte_T, h3p_evaluations_above_lte_T);
      ! 20 K and 5000 K are nodes and are inside, so the records count
      ! STRICT excursions only.  A nonfinite temperature is recorded on its
      ! own; NaN evaluates to the T -> 0 limit, zero emission, and +infinity
      ! to the held 5000 K value.
      !
      ! THE NON-LTE FACTOR.  s(T, [H2]) is the departure factor of Miller et
      ! al. (2013) Table 6, defined by their eq. 8 as the ratio of the
      ! vibrational-level sum with the detailed-balance (Oka & Epp)
      ! populations to the same sum with the LTE populations.  Both sums are
      ! taken over the same vibrational band strengths (Dinelli et al. 1992),
      ! so s is a ratio normalized by its own LTE sum and does not contain
      ! the Miller line-list sum: it does not inherit the excess above and
      ! multiplies the MiZATeP W unchanged (md/h3p_cooling_cause_20261010.md,
      ! "Non-LTE factor s").  The emission rows of their Table 6 are
      ! E_Miller x s and are NOT used as absolute emission.  Not checked:
      ! how well a vibrational-level model with those bands represents the
      ! high-J, high-energy upper states that carry 18 per cent of the
      ! MiZATeP LTE emission at 2000 K.
      ! Its only collider is H2, through the proton-hopping reaction
      ! H3+(v=m) + H2 -> H2 + H3+(v=n) with the Oka & Epp rate coefficient
      ! 2e-15 m^3 s^-1; no other collision partner enters, and the density
      ! it depends on is the H2 number density alone.  The paper states that
      ! the Table 6 values MAY BE UPPER LIMITS, especially at low densities,
      ! because that rate coefficient is its largest uncertainty.
      !
      ! COLLIDER DOMAIN AND THE LOW-COLLIDER LIMIT.  Table 6 is tabulated at
      ! [H2] = 1e12 to 1e20 m^-3, that is 1e6 to 1e14 cm^-3.  Below 1e6 cm^-3
      ! radiative decay empties the emitting levels faster than collisions
      ! populate them, so each collisional excitation is followed by a decay
      ! and the emission of one H3+ ion is set by the collision rate: s is
      ! linear in n(H2) and vanishes with it.  That limit is adopted as
      ! the evaluation below the table,
      !
      !   s(T, n_H2 < 1e6) = s(T, 1e6) * n_H2/1e6,
      !
      ! and records the evaluation as made below the tabulated collider
      ! range (h3p_evaluations_below_collider below).  The record is
      ! informational: the coolant stays defined where the model has a known
      ! analytic limit.
      ! Above 1e14 cm^-3 the table edge is held (s = s(T,1e14), which is
      ! 0.9985 to 1.0000, so the residual departure from LTE at and above the
      ! last tabulated column is at most 0.15 per cent); no extrapolation is
      ! made above the table, and the evaluation is recorded there too
      ! (h3p_evaluations_above_collider).
      !
      ! Reference PDFs: references/Mizus_2017MNRAS_468_1717.pdf (section 5,
      ! Table 7), references/Miller_2013_JPCA_117_9770.pdf (Table 6, eq. 8).
      ! NaN-safe bracketing style of the cooling-table interpolators (code
      ! review 2026-07-02).

      use h3p_mizatep_cooling_table, only: h3p_cf_t_first, h3p_cf_t_last, &
                                           h3p_cf_nodes, h3p_cf_w_erg
      implicit none
      private
      public :: h3p_lte_emission_mizatep, h3p_nonlte_factor,              &
                h3p_cooling_rate, h3p_net_cooling_rate,                   &
                h3p_reset_domain_records
      public :: h3p_evaluations_below_collider,                           &
                h3p_evaluations_above_collider,                           &
                h3p_evaluations_below_lte_T,                              &
                h3p_evaluations_above_lte_T,                              &
                h3p_evaluations_outside_nonlte_T,                         &
                h3p_evaluations_nonfinite_T,                              &
                h3p_evaluations_nonfinite_collider
      ! Where one argument stands relative to a tabulated range, for a
      ! caller that maps a STATE rather than counting the evaluations of a
      ! run: the same three tests the records below are taken with, with no
      ! side effect of their own.
      public :: h3p_lte_temperature_domain,                               &
                h3p_nonlte_row_temperature_domain, h3p_collider_domain
      public :: H3P_DOMAIN_INSIDE, H3P_DOMAIN_BELOW, H3P_DOMAIN_ABOVE,    &
                H3P_DOMAIN_NONFINITE

      real*8, parameter :: fourpi = 12.566370614359172d0

      ! WHAT THESE COUNT.  Each is the number of EVALUATIONS, accumulated
      ! over the whole run, whose argument met the stated condition.  A cell
      ! visited many times contributes many times, one cell can meet several
      ! conditions, and an evaluation made inside a trial that was then
      ! rejected contributes like one inside an accepted state.  They are
      ! therefore the history of the run and are not a property of any one
      ! state; the domain map of a single state is a separate measurement
      ! (certification.f90, h3p_cooling_domain_map_of_state), taken with the
      ! three classifying functions below.  Informational either way: none
      ! of them changes a rate.
      integer, save :: h3p_evaluations_below_collider     = 0  ! n_H2 < 1e6 cm^-3 (collisional limit used)
      integer, save :: h3p_evaluations_above_collider     = 0  ! n_H2 > 1e14 cm^-3 (table edge held)
      integer, save :: h3p_evaluations_below_lte_T        = 0  ! T < 20 K   (Boltzmann continuation)
      integer, save :: h3p_evaluations_above_lte_T        = 0  ! T > 5000 K (emission held)
      integer, save :: h3p_evaluations_outside_nonlte_T   = 0  ! T outside 300-5000 K (Table 6 row clamped)
      integer, save :: h3p_evaluations_nonfinite_T        = 0  ! T not an ordinary real
      integer, save :: h3p_evaluations_nonfinite_collider = 0  ! n_H2 not an ordinary real

      ! Where an argument stands relative to a tabulated range.  BELOW and
      ! ABOVE are strict excursions, so an argument sitting exactly on an
      ! endpoint is INSIDE: the table has a node or a row there.  NONFINITE
      ! is its own answer and is never folded into BELOW.
      integer, parameter :: H3P_DOMAIN_INSIDE    = 0
      integer, parameter :: H3P_DOMAIN_BELOW     = 1
      integer, parameter :: H3P_DOMAIN_ABOVE     = 2
      integer, parameter :: H3P_DOMAIN_NONFINITE = 3

      ! Ends of the MiZATeP table [K] and its unit conversion, erg to J.
      real*8, parameter :: T_lte_lo = dble(h3p_cf_t_first)
      real*8, parameter :: T_lte_hi = dble(h3p_cf_t_last)
      real*8, parameter :: joule_per_erg = 1.0d-7

      ! --- Table 6 non-LTE scaling s(T, n_H2) --------------------------- !
      ! Grid: T rows (K) x log10(n_H2 [cm^-3]) columns 6,8,10,12,14
      ! ([H2] = 1e12..1e20 m^-3 in the paper).
      integer, parameter :: nTs = 11, nNs = 5
      real*8, parameter :: sT(nTs) = [ 300.d0, 600.d0, 1000.d0, 1500.d0, &
           2000.d0, 2500.d0, 3000.d0, 3500.d0, 4000.d0, 4500.d0, 5000.d0 ]
      real*8, parameter :: sLogN(nNs) = [ 6.d0, 8.d0, 10.d0, 12.d0, 14.d0 ]
      real*8, parameter :: n_tab_lo = 1.0d6   ! lowest tabulated collider density [cm^-3]
      real*8, parameter :: n_tab_hi = 1.0d14  ! highest, 10**sLogN(nNs) [cm^-3]
      real*8, parameter :: sTab(nTs,nNs) = reshape( [                    &
      ! log n_H2=6      (T = 300..5000)
        0.0067d0, 0.0011d0, 0.0013d0, 0.0013d0, 0.0011d0, 0.0010d0,      &
        0.0009d0, 0.0008d0, 0.0007d0, 0.0007d0, 0.0007d0,                &
      ! log n_H2=8
        0.3931d0, 0.0313d0, 0.0108d0, 0.0064d0, 0.0049d0, 0.0042d0,      &
        0.0038d0, 0.0036d0, 0.0034d0, 0.0033d0, 0.0033d0,                &
      ! log n_H2=10
        0.9848d0, 0.7449d0, 0.4955d0, 0.3640d0, 0.2894d0, 0.2469d0,      &
        0.2220d0, 0.2064d0, 0.1961d0, 0.1889d0, 0.1836d0,                &
      ! log n_H2=12
        0.9998d0, 0.9965d0, 0.9866d0, 0.9701d0, 0.9499d0, 0.9299d0,      &
        0.9136d0, 0.9014d0, 0.8923d0, 0.8854d0, 0.8802d0,                &
      ! log n_H2=14
        1.0000d0, 1.0000d0, 0.9999d0, 0.9997d0, 0.9995d0, 0.9992d0,      &
        0.9990d0, 0.9988d0, 0.9987d0, 0.9985d0, 0.9985d0 ],              &
        [nTs,nNs] )

      contains

      ! ------------------------------------------------------------------ !

      ! Zero the evaluation history above, so that what follows is counted
      ! on its own.
      subroutine h3p_reset_domain_records()
      h3p_evaluations_below_collider     = 0
      h3p_evaluations_above_collider     = 0
      h3p_evaluations_below_lte_T        = 0
      h3p_evaluations_above_lte_T        = 0
      h3p_evaluations_outside_nonlte_T   = 0
      h3p_evaluations_nonfinite_T        = 0
      h3p_evaluations_nonfinite_collider = 0
      end subroutine h3p_reset_domain_records

      ! ------------------------------------------------------------------ !

      ! Whether x is an ordinary real: no NaN and no infinity.  NaN fails
      ! every comparison including with itself and an infinity exceeds the
      ! largest representable finite value, so the two tests together cover
      ! both.  Written out rather than taken from ieee_arithmetic so that the
      ! generated module dependency graph stays over the source tree, as
      ! finite_real (ionization_equilibrium.f90) is.
      pure logical function ordinary_real(x) result(ok)
      real*8, intent(in) :: x
      ok = (x .eq. x) .and. (abs(x) .le. huge(1.0d0))
      end function ordinary_real

      ! Where T stands relative to the 20-5000 K nodes of the MiZATeP table.
      pure integer function h3p_lte_temperature_domain(T) result(code)
      real*8, intent(in) :: T
      if (.not. ordinary_real(T)) then
         code = H3P_DOMAIN_NONFINITE
      else if (T .lt. T_lte_lo) then
         code = H3P_DOMAIN_BELOW
      else if (T .gt. T_lte_hi) then
         code = H3P_DOMAIN_ABOVE
      else
         code = H3P_DOMAIN_INSIDE
      endif
      end function h3p_lte_temperature_domain

      ! Where T stands relative to the 300-5000 K rows of Table 6.
      pure integer function h3p_nonlte_row_temperature_domain(T)          &
                            result(code)
      real*8, intent(in) :: T
      if (.not. ordinary_real(T)) then
         code = H3P_DOMAIN_NONFINITE
      else if (T .lt. sT(1)) then
         code = H3P_DOMAIN_BELOW
      else if (T .gt. sT(nTs)) then
         code = H3P_DOMAIN_ABOVE
      else
         code = H3P_DOMAIN_INSIDE
      endif
      end function h3p_nonlte_row_temperature_domain

      ! Where the collider density stands relative to the 1e6-1e14 cm^-3
      ! columns of Table 6.  BELOW is the analytic collisional limit of the
      ! module header, which is a statement of the model and not an
      ! extrapolation outside it; ABOVE is the held table edge.
      pure integer function h3p_collider_domain(nH2) result(code)
      real*8, intent(in) :: nH2
      if (.not. ordinary_real(nH2)) then
         code = H3P_DOMAIN_NONFINITE
      else if (nH2 .lt. n_tab_lo) then
         code = H3P_DOMAIN_BELOW
      else if (nH2 .gt. n_tab_hi) then
         code = H3P_DOMAIN_ABOVE
      else
         code = H3P_DOMAIN_INSIDE
      endif
      end function h3p_collider_domain

      ! ------------------------------------------------------------------ !

      ! LTE emission of one H3+ molecule into one steradian, W(T)
      ! [W molecule^-1 sr^-1], from the MiZATeP cooling function with the
      ! interpolation and the domain of the module header.
      double precision function h3p_lte_emission_mizatep(T) result(W)
      real*8, intent(in) :: T
      real*8 :: tt, t_k, t_k1, f
      integer :: i
      ! THE RECORD, which is interval membership: T = 20 K and T = 5000 K
      ! are nodes and count as nothing.
      select case (h3p_lte_temperature_domain(T))
      case (H3P_DOMAIN_BELOW)
!$omp atomic update
         h3p_evaluations_below_lte_T = h3p_evaluations_below_lte_T + 1
      case (H3P_DOMAIN_ABOVE)
!$omp atomic update
         h3p_evaluations_above_lte_T = h3p_evaluations_above_lte_T + 1
      case (H3P_DOMAIN_NONFINITE)
!$omp atomic update
         h3p_evaluations_nonfinite_T = h3p_evaluations_nonfinite_T + 1
      end select
      ! THE EVALUATION.  The .not.(x .gt. 0) form sends a NaN, and every
      ! T <= 0, to the T -> 0 limit of the Boltzmann form: no emission.
      tt = T
      if (.not. (tt .gt. 0.0d0)) then
         W = 0.0d0
         return
      endif
      if (tt .ge. T_lte_hi) then                    ! last node, held above
         W = h3p_cf_w_erg(h3p_cf_nodes)*joule_per_erg
         return
      endif
      ! Interval [t_k, t_k + 1 K] holding tt; below the first node the
      ! first interval, whose Boltzmann form is continued down to T -> 0.
      if (tt .lt. T_lte_lo) then
         i = 1
      else
         i = int(tt) - h3p_cf_t_first + 1
      endif
      t_k  = dble(h3p_cf_t_first + i - 1)
      t_k1 = t_k + 1.0d0
      f = (1.0d0/tt - 1.0d0/t_k)/(1.0d0/t_k1 - 1.0d0/t_k)
      W = h3p_cf_w_erg(i)*(h3p_cf_w_erg(i+1)/h3p_cf_w_erg(i))**f          &
          *joule_per_erg
      end function h3p_lte_emission_mizatep

      ! ------------------------------------------------------------------ !

      ! Non-LTE departure factor s(T, n_H2), Miller+2013 Table 6, a power law
      ! in n_H2 between the tabulated columns and linear in T between the
      ! tabulated rows (s_table below says why).  Below the lowest tabulated
      ! collider density the collisional limit of the module header is used,
      ! so s and the cooling vanish linearly with n_H2; above the highest tabulated one the
      ! table edge is held; outside 300-5000 K the nearest tabulated row is
      ! used.  Each of those three is recorded, and so is a nonfinite
      ! argument.
      double precision function h3p_nonlte_factor(T, nH2) result(s)
      real*8, intent(in) :: T, nH2
      real*8 :: tt, nn, ln
      ! The records first, taken on the arguments as given: 300 K and
      ! 5000 K are tabulated rows and 1e6 and 1e14 cm^-3 tabulated columns,
      ! so an argument sitting on one of them counts as nothing.
      select case (h3p_nonlte_row_temperature_domain(T))
      case (H3P_DOMAIN_BELOW, H3P_DOMAIN_ABOVE)
!$omp atomic update
         h3p_evaluations_outside_nonlte_T =                               &
              h3p_evaluations_outside_nonlte_T + 1
      case (H3P_DOMAIN_NONFINITE)
!$omp atomic update
         h3p_evaluations_nonfinite_T = h3p_evaluations_nonfinite_T + 1
      end select
      select case (h3p_collider_domain(nH2))
      case (H3P_DOMAIN_BELOW)
!$omp atomic update
         h3p_evaluations_below_collider =                                 &
              h3p_evaluations_below_collider + 1
      case (H3P_DOMAIN_ABOVE)
!$omp atomic update
         h3p_evaluations_above_collider =                                 &
              h3p_evaluations_above_collider + 1
      case (H3P_DOMAIN_NONFINITE)
!$omp atomic update
         h3p_evaluations_nonfinite_collider =                             &
              h3p_evaluations_nonfinite_collider + 1
      end select
      ! The evaluation, with the clamps as they are: a nonfinite argument
      ! lands on the low end of the rows and on a zero collider density,
      ! where the collisional limit returns zero.
      tt = T
      if (.not. (tt .gt. sT(1))) tt = sT(1)         ! NaN-safe
      if (tt .gt. sT(nTs))       tt = sT(nTs)
      nn = nH2
      if (.not. (nn .gt. 0.0d0)) nn = 0.0d0         ! NaN-safe
      if (nn .lt. n_tab_lo) then
         s = s_table(tt, sLogN(1))*(nn/n_tab_lo)    ! collisional limit
         return
      endif
      ln = log10(nn)
      if (ln .gt. sLogN(nNs)) ln = sLogN(nNs)       ! table edge held
      s = s_table(tt, ln)
      end function h3p_nonlte_factor

      ! Interpolation of Table 6 on its own grid; both arguments must
      ! already lie inside it.
      !
      ! IN n_H2 THE INTERPOLANT IS A POWER LAW BETWEEN COLUMNS, i.e. log s
      ! linear in log n_H2.  The emission per H3+ ion can grow at most as
      ! fast as the collision rate that populates the emitting levels, so
      ! the local index d ln s / d ln n_H2 lies between 0 (the LTE limit)
      ! and 1 (the collisional limit the module header adopts below the
      ! table), and the node-to-node indices of Table 6 all do (0.00 to
      ! 0.89).  A power law between columns keeps each interval's index at
      ! that node-to-node value.  An interpolant linear in s against log n,
      ! used before 2026-09-24, does not: where s rises by two decades
      ! across one interval (e.g. 0.0049 to 0.2894 at 2000 K between 1e8 and
      ! 1e10 cm^-3) its local index reaches 12.6 just above the lower column
      ! against 0.17 just below it, and over r = 1.25-1.40 R_p of a
      ! well-mixed LHS 1140 b molecular state (He/H 0.083) it put the H3+
      ! cooling 1.8 to 5.6 times above the power law.  The paper gives s only at its columns and states
      ! no interpolation; every Table 6 value is positive, so the power law
      ! is defined everywhere on the grid.
      ! IN T THE INTERPOLANT STAYS LINEAR between rows 300-500 K apart.  No
      ! bound like the one above fixes its form; s changes between adjacent
      ! rows by under 30 per cent in 42 of the 50 row intervals, and by the
      ! factors 12.6 and 2.9 over 300-600 and 600-1000 K at 1e8 cm^-3 and
      ! 6.1 over 300-600 K at 1e6 cm^-3, where the form of the T
      ! interpolant matters and is not constrained by the paper.
      double precision function s_table(tt, ln) result(s)
      real*8, intent(in) :: tt, ln
      real*8 :: ft, fn, s_cooler_row, s_warmer_row
      integer :: it, in
      it = 1
      do while (it .lt. nTs-1 .and. sT(it+1) .lt. tt)
         it = it + 1
      enddo
      ft = (tt - sT(it))/(sT(it+1) - sT(it))
      in = 1 + int((ln - sLogN(1))/2.0d0)           ! uniform step 2 in log10
      if (in .gt. nNs-1) in = nNs-1
      fn = (ln - sLogN(in))/2.0d0
      s_cooler_row = sTab(it,  in)*(sTab(it,  in+1)/sTab(it,  in))**fn
      s_warmer_row = sTab(it+1,in)*(sTab(it+1,in+1)/sTab(it+1,in))**fn
      s    = (1.d0-ft)*s_cooler_row + ft*s_warmer_row
      end function s_table

      ! ------------------------------------------------------------------ !

      ! Volumetric H3+ cooling rate [erg s^-1 cm^-3]:
      !   Lambda = n_H3+ * 4 pi * W(T) * s(T,n_H2) * 1e7.
      double precision function h3p_cooling_rate(T, nH3p, nH2) result(lam)
      real*8, intent(in) :: T, nH3p, nH2
      lam = nH3p*fourpi*h3p_lte_emission_mizatep(T)                       &
                *h3p_nonlte_factor(T,nH2)*1.0d7
      end function h3p_cooling_rate

      ! ------------------------------------------------------------------ !

      ! NET H3+ infrared cooling [erg s^-1 cm^-3]: the emission above minus
      ! the absorption of the thermal infrared radiation of the lower
      ! atmosphere, a blackbody at T_rad filling a fraction W_dil of the
      ! solid angle (W_dil = 0 recovers h3p_cooling_rate exactly).
      !
      ! CLOSURE.  The same net-exchange form the other infrared channels of
      ! the molecular layer use (molecular_infrared_cooling.f90, eq. 1):
      !
      !   Lambda_net = n_H3+ 4 pi s(T,n_H2) [ W(T) - W_dil W(T_rad) ]
      !
      ! The absorbed power of one molecule is
      ! 4 pi W_dil Int sigma_nu B_nu(T_rad) dnu, and Kirchhoff's law at the
      ! radiating temperature identifies that integral, evaluated with the
      ! cross section AT T_rad, with the LTE emission itself: W(T_rad).  So
      ! the one cooling function serves both terms.
      !
      ! WHY NOT ONE EFFECTIVE TRANSITION.  Collapsing the emission onto the
      ! nu2-band transition (hc*2521.3 cm^-1 / k = 3627.5 K) and writing the
      ! absorption as Lambda_emit*nbar*[exp(Ek/T) - 1] pairs the TOTAL
      ! emission -- a sum over the nu2 fundamental, its hot bands, the
      ! overtones and the forbidden rotational lines -- with the Boltzmann
      ! factor of ONE of them.  It is self-consistent only where
      ! W(T) exp(Ek/T) is independent of T, which is what a single transition
      ! with a saturated lower level would give; measured on the MiZATeP
      ! table that product is 9.5e-19 at 300 K, 7.2e-13 at 100 K and 1.5e22
      ! at 30 K, because the low-temperature emission is carried by
      ! transitions far below 3627.5 K, so that form heats a cold gas at many
      ! decades its own emission.  The form above is bounded for any T
      ! because the absorption does not reference the gas temperature at all.
      !
      ! The three limits it has to have, and does:
      !   T = T_rad, W_dil = 1  ->  exactly zero, to machine precision:
      !       gas buried in a blackbody at its own temperature neither cools
      !       nor heats.
      !   T -> 0                ->  emission -> 0, absorption finite: the
      !       band heats at the rate the field supplies, not faster.
      !   W_dil = 0             ->  the emission-only rate, unchanged.
      ! The radiative equilibrium temperature is the root of
      ! W(T_eq) = W_dil W(T_rad); it has no closed form and is 958.5 K for
      ! T_rad = 1140 K, W_dil = 1/2 (MEASURED on the MiZATeP table).
      !
      ! WHERE IT DIFFERS FROM THE OTHER THREE CHANNELS.  H2O and CO are band
      ! absorbers with tabulated sigma_b(T), so their absorption keeps the
      ! cross section at the GAS temperature and only the Planck function at
      ! T_rad; H2 is summed transition by transition with the full two-level
      ! factor.  Here the cooling function is the product of cross section
      ! and Planck function already integrated over every line, so the cross
      ! section cannot be separated from the weighting and is frozen at
      ! T_rad.  The error that freezing makes is the temperature
      ! dependence of the band strength alone -- the fraction of molecules in
      ! the absorbing lower states, which rises toward 1 as T falls, so the
      ! absorption above is if anything a slight underestimate at low T.  It
      ! is exact at T = T_rad, which is where the fixed point sits.
      !
      ! VALIDITY.  (i) The lower atmosphere is taken to be black at 3-4 um,
      ! which an H2 atmosphere at the microbar base and below is (H2
      ! collision-induced absorption plus the H2O/CH4/CO bands), but the
      ! incident field is NOT attenuated by the intervening H3+ column, so
      ! where those lines are self-shielding this overestimates the
      ! absorption -- the same trapping would also reduce the emission term,
      ! which is not modeled either.  (ii) The non-LTE departure factor
      ! multiplies BOTH terms.  It has to: s < 1 with the absorption left at
      ! its LTE value would heat a gas that is HOTTER than the field, which
      ! no exchange between two temperatures may do.  Read this way s is the
      ! fraction of molecules radiatively coupled at the local density, and
      ! it scales the rate without moving the equilibrium temperature.
      ! Miller et al.'s Table 6 is a vacuum departure factor -- collisions
      ! against spontaneous decay, no incident field -- and a field strong
      ! enough to matter here pumps the levels back toward LTE, so the true
      ! departure is smaller than s and this underestimates the magnitude of
      ! the exchange, not its sign or its fixed point.
      double precision function h3p_net_cooling_rate                      &
                                 (T, nH3p, nH2, T_rad, W_dil) result(lam)
      real*8, intent(in) :: T, nH3p, nH2, T_rad, W_dil
      lam = h3p_cooling_rate(T, nH3p, nH2)
      if (.not. (W_dil .gt. 0.0d0)) return
      lam = lam - nH3p*fourpi*h3p_lte_emission_mizatep(T_rad)             &
                             *h3p_nonlte_factor(T,nH2)*W_dil*1.0d7
      end function h3p_net_cooling_rate

      ! End of module
      end module h3p_cooling
